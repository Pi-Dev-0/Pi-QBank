import 'dart:convert';

/// The three test shapes the JSON test maker can produce.
///
/// [label] is what the UI and the share endpoint use. [savedTestType] is the
/// value `SavedTestsPage` expects if a generated test is ever stored as a draft.
enum TestType {
  mcq('MCQ', 'MCQ Test'),
  short('Short Question', 'Short Question'),
  creative('Creative Question', 'Creative Question');

  const TestType(this.label, this.savedTestType);

  final String label;
  final String savedTestType;

  static TestType? tryFromLabel(String? label) {
    for (final type in values) {
      if (type.label == label || type.savedTestType == label) return type;
    }
    return null;
  }

  static TestType fromLabel(String? label) {
    return tryFromLabel(label) ?? TestType.mcq;
  }
}

/// A user-facing problem with the pasted JSON.
class TestFormatException implements Exception {
  TestFormatException(this.message);

  final String message;

  @override
  String toString() => message;
}

/// A parsed and validated test, ready for a runner.
class ParsedTest {
  const ParsedTest({
    required this.type,
    required this.topic,
    required this.questions,
  });

  final TestType type;
  final String topic;
  final List<Map<String, dynamic>> questions;

  int get length => questions.length;

  Map<String, dynamic> toJson() => {
        'topic': topic,
        'questions': questions,
      };

  /// Compact JSON for the runners and the share endpoint.
  String get normalizedJson => jsonEncode(toJson());

  /// Indented JSON for the editor, so the user can inspect what was accepted.
  String get prettyJson => const JsonEncoder.withIndent('  ').convert(toJson());
}

/// Extract the first balanced JSON object from an AI response.
///
/// AI answers often arrive wrapped in ```json fences or surrounded by prose.
/// A simple `indexOf('{')` / `lastIndexOf('}')` pair breaks when a brace appears
/// inside a string, so this walks the text and tracks strings and escapes.
String cleanAiJson(String raw) {
  var text = raw.trim();
  if (text.isEmpty) {
    throw TestFormatException(
      'Paste the JSON generated by the AI first.',
    );
  }

  text = text.replaceFirst(
    RegExp(r'^```(?:json)?\s*', caseSensitive: false),
    '',
  );
  text = text.replaceFirst(RegExp(r'\s*```\s*$'), '');
  text = text.trim();

  final start = text.indexOf('{');
  if (start == -1) {
    throw TestFormatException(
      'No JSON object found. Paste the AI response exactly as it was returned.',
    );
  }

  var depth = 0;
  var inString = false;
  var escaped = false;

  for (var i = start; i < text.length; i++) {
    final ch = text[i];

    if (inString) {
      if (escaped) {
        escaped = false;
      } else if (ch == '\\') {
        escaped = true;
      } else if (ch == '"') {
        inString = false;
      }
      continue;
    }

    if (ch == '"') {
      inString = true;
    } else if (ch == '{') {
      depth++;
    } else if (ch == '}') {
      depth--;
      if (depth == 0) {
        return text.substring(start, i + 1);
      }
    }
  }

  throw TestFormatException(
    'The JSON object is incomplete. Check for a missing closing brace.',
  );
}

/// Normalize the many option shapes an AI may return into the contract the
/// MCQ runner expects: keys `"1"`..`"n"` and `correct_answer` as one of those
/// keys.
///
/// The runner maps the numeric key to a letter/bubble, so an `"A"` key renders
/// as `"A"` for every option. This is why the normalization matters.
Map<String, dynamic> normalizeMcqQuestion(Map<String, dynamic> raw) {
  final rawOptions = raw['options'];
  final entries = <MapEntry<String, dynamic>>[];

  if (rawOptions is Map) {
    for (final entry in rawOptions.entries) {
      entries.add(MapEntry('${entry.key}', entry.value));
    }
  } else if (rawOptions is List) {
    for (var i = 0; i < rawOptions.length; i++) {
      entries.add(MapEntry('${i + 1}', rawOptions[i]));
    }
  }

  final correctRaw = '${raw['correct_answer'] ?? ''}'.trim();
  var correctIndex = -1;

  // The answer may already be a key ("A", "1", "a").
  for (var i = 0; i < entries.length; i++) {
    if (entries[i].key.toUpperCase() == correctRaw.toUpperCase()) {
      correctIndex = i;
      break;
    }
  }

  // The answer may be a letter: A -> 0, B -> 1, ...
  if (correctIndex == -1 && correctRaw.isNotEmpty) {
    final upper = correctRaw.toUpperCase();
    final code = upper.codeUnitAt(0);
    if (code >= 65 && code <= 90) {
      final index = code - 65;
      if (index < entries.length) correctIndex = index;
    } else {
      // Bengali option letters, in case the AI ignores the numeric-key rule.
      const bengaliLetters = ['ক', 'খ', 'গ', 'ঘ'];
      final index = bengaliLetters.indexOf(correctRaw);
      if (index >= 0 && index < entries.length) correctIndex = index;
    }
  }

  // The answer may be the option text rather than its key.
  if (correctIndex == -1) {
    for (var i = 0; i < entries.length; i++) {
      if ('${entries[i].value}'.trim() == correctRaw) {
        correctIndex = i;
        break;
      }
    }
  }

  final options = <String, dynamic>{};
  for (var i = 0; i < entries.length; i++) {
    options['${i + 1}'] = entries[i].value;
  }

  return {
    ...raw,
    'options': options,
    'correct_answer': correctIndex == -1 ? correctRaw : '${correctIndex + 1}',
  };
}

/// Validate one test type and return normalized question maps.
///
/// Throws [TestFormatException] with the question number so the user can fix
/// the exact item that is wrong instead of getting a blank test screen.
List<Map<String, dynamic>> validateQuestions(
  List<dynamic> raw,
  TestType type,
) {
  final out = <Map<String, dynamic>>[];

  for (var i = 0; i < raw.length; i++) {
    final item = raw[i];
    if (item is! Map) {
      throw TestFormatException('Question ${i + 1} is not an object.');
    }

    final q = Map<String, dynamic>.from(item);

    switch (type) {
      case TestType.mcq:
        final question = '${q['question'] ?? ''}'.trim();
        if (question.isEmpty) {
          throw TestFormatException('Question ${i + 1} has no text.');
        }

        final normalized = normalizeMcqQuestion(q);
        final options = normalized['options'];
        if (options is! Map || options.isEmpty) {
          throw TestFormatException(
            'Question ${i + 1} has no options.',
          );
        }
        if (options.length < 2) {
          throw TestFormatException(
            'Question ${i + 1} needs at least two options.',
          );
        }

        final correct = '${normalized['correct_answer'] ?? ''}'.trim();
        final optionKeys = options.keys.map((key) => '$key').toSet();
        if (!optionKeys.contains(correct)) {
          throw TestFormatException(
            'Question ${i + 1}: correct_answer "$correct" matches no option.',
          );
        }

        out.add({...normalized, 'question': question});
        break;

      case TestType.short:
        final question = '${q['question'] ?? ''}'.trim();
        final answer = '${q['answer'] ?? ''}'.trim();
        if (question.isEmpty) {
          throw TestFormatException('Question ${i + 1} has no text.');
        }
        if (answer.isEmpty) {
          throw TestFormatException('Question ${i + 1} has no answer.');
        }
        out.add({...q, 'question': question, 'answer': answer});
        break;

      case TestType.creative:
        final stem = '${q['stem'] ?? ''}'.trim();
        if (stem.isEmpty) {
          throw TestFormatException('Question ${i + 1} has no stem.');
        }

        final rawSubs = q['sub_questions'];
        if (rawSubs is! List || rawSubs.isEmpty) {
          throw TestFormatException(
            'Question ${i + 1} has no sub-questions.',
          );
        }

        final subs = <Map<String, dynamic>>[];
        for (var j = 0; j < rawSubs.length; j++) {
          final sub = rawSubs[j];
          if (sub is! Map) {
            throw TestFormatException(
              'Question ${i + 1}, sub-question ${j + 1} is not an object.',
            );
          }

          final subMap = Map<String, dynamic>.from(sub);
          final text = '${subMap['text'] ?? ''}'.trim();
          if (text.isEmpty) {
            throw TestFormatException(
              'Question ${i + 1}, sub-question ${j + 1} has no text.',
            );
          }

          final marks = subMap['marks'];
          final marksValue =
              marks is num ? marks.toInt() : int.tryParse('$marks') ?? (j + 1);

          subs.add({
            ...subMap,
            'text': text,
            'marks': marksValue,
          });
        }

        out.add({
          ...q,
          'question_number': q['question_number'] ?? i + 1,
          'stem': stem,
          'sub_questions': subs,
        });
        break;
    }
  }

  return out;
}

/// Parse the raw AI response into a validated [ParsedTest].
ParsedTest parseTest(String raw, TestType type) {
  final cleaned = cleanAiJson(raw);

  dynamic decoded;
  try {
    decoded = jsonDecode(cleaned);
  } on FormatException catch (e) {
    throw TestFormatException('Invalid JSON: ${e.message}');
  }

  if (decoded is! Map) {
    throw TestFormatException('The JSON root must be an object.');
  }

  final rawQuestions = decoded['questions'];
  if (rawQuestions is! List || rawQuestions.isEmpty) {
    throw TestFormatException(
      'The JSON must contain a non-empty "questions" list.',
    );
  }

  final questions = validateQuestions(rawQuestions, type);
  final topic = '${decoded['topic'] ?? ''}'.trim();

  return ParsedTest(
    type: type,
    topic: topic.isEmpty ? 'Generated Test' : topic,
    questions: questions,
  );
}

/// Turn short questions into the line format `ShortQuestionPage` understands.
///
/// Newlines inside a question or answer are collapsed because the runner parses
/// one question per numbered line. The answer label follows the test language.
String formatShortQuestions(
  List<Map<String, dynamic>> questions,
  String language,
) {
  final answerLabel = language == 'বাংলা' ? 'উত্তর' : 'Answer';
  final buffer = StringBuffer();
  var number = 0;

  for (final q in questions) {
    final question =
        '${q['question'] ?? ''}'.replaceAll(RegExp(r'\s*\n\s*'), ' ').trim();
    final answer =
        '${q['answer'] ?? ''}'.replaceAll(RegExp(r'\s*\n\s*'), ' ').trim();

    if (question.isEmpty) continue;

    number++;
    buffer
      ..writeln('$number. $question')
      ..writeln('$answerLabel: $answer')
      ..writeln();
  }

  return buffer.toString().trim();
}

/// Plain-text version of creative questions, used by the preview dialog's copy
/// action.
String formatCreativeQuestions(
  List<Map<String, dynamic>> questions,
  String language,
) {
  final marksLabel = language == 'বাংলা' ? 'নম্বর' : 'marks';
  final buffer = StringBuffer();

  for (var i = 0; i < questions.length; i++) {
    final q = questions[i];
    buffer.writeln(
      '${q['question_number'] ?? i + 1}. ${q['stem'] ?? ''}',
    );

    final subs = q['sub_questions'];
    if (subs is List) {
      for (final sub in subs) {
        if (sub is Map) {
          buffer.writeln(
            '${sub['label']}) ${sub['text']} '
            '(${sub['marks']} $marksLabel)',
          );
        }
      }
    }
    buffer.writeln();
  }

  return buffer.toString().trim();
}
