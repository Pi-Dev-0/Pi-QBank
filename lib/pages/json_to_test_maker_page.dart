  Widget _buildJsonStatus(({bool valid, String message, int count}) status) {
    final raw = _jsonController.text.trim();
    if (raw.isEmpty) {
      return Text(
        'Paste the AI response above to validate it.',
        style: TextStyle(fontSize: 12, color: Colors.grey.shade600),
      );
    }

    final mismatch = status.valid && status.count != _questionCount;
    final color = !status.valid
        ? Colors.red.shade700
        : mismatch
            ? Colors.orange.shade800
            : Colors.green.shade700;
    final icon = !status.valid
        ? Icons.error_outline
        : mismatch
            ? Icons.info_outline
            : Icons.check_circle_outline;
    final message = mismatch
        ? 'Valid JSON · ${status.count} questions '
            '(you asked for $_questionCount)'
        : status.message;

    return Row(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Icon(icon, size: 16, color: color),
        const SizedBox(width: 6),
        Expanded(
          child: Text(
            message,
            maxLines: 2,
            overflow: TextOverflow.ellipsis,
            style: TextStyle(fontSize: 12, color: color),
          ),
        ),
      ],
    );
  }

