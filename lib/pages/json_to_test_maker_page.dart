class JsonToTestMakerPage extends StatefulWidget {
  const JsonToTestMakerPage({super.key});

  @override
  State<JsonToTestMakerPage> createState() => _JsonToTestMakerPageState();
}

class _JsonToTestMakerPageState extends State<JsonToTestMakerPage>
    with SingleTickerProviderStateMixin {
  final TextEditingController _jsonController = TextEditingController();
  final TextEditingController _countController =
      TextEditingController(text: '10');
  final TextEditingController _durationController =
      TextEditingController(text: '10');
  final ImagePicker _imagePicker = ImagePicker();
  final List<XFile> _selectedImages = [];
  final TestShareService _shareService = TestShareService(
    contentType: AppConfig.testShareContentType.isNotEmpty
        ? AppConfig.testShareContentType
        : (kIsWeb ? 'text/plain;charset=utf-8' : 'application/json'),
  );

  static const int _maxImages = 5;

  String _selectedTestType = TestType.mcq.label;
  String _selectedLanguage = 'বাংলা';
  bool _isSharing = false;
  bool _isPickingImages = false;

  late AnimationController _animationController;
  late Animation<double> _fadeAnimation;
  late Animation<Offset> _slideAnimation;

  TestType get _testType => TestType.fromLabel(_selectedTestType);

  int get _questionCount =>
      (int.tryParse(_countController.text) ?? 10).clamp(1, 100);

  int get _durationMinutes =>
      (int.tryParse(_durationController.text) ?? 10).clamp(1, 180);

  bool get _hasRangeWarning {
    final count = int.tryParse(_countController.text);
    final duration = int.tryParse(_durationController.text);
    return count == null ||
        count < 1 ||
        count > 100 ||
        duration == null ||
        duration < 1 ||
        duration > 180;
  }

  @override
  void initState() {
    super.initState();
    _animationController = AnimationController(
      duration: const Duration(milliseconds: 600),
      vsync: this,
    );
    _fadeAnimation = Tween<double>(begin: 0.0, end: 1.0).animate(
      CurvedAnimation(parent: _animationController, curve: Curves.easeInOut),
    );
    _slideAnimation = Tween<Offset>(
      begin: const Offset(0, 0.2),
      end: Offset.zero,
    ).animate(CurvedAnimation(
      parent: _animationController,
      curve: Curves.easeOutBack,
    ));
    _animationController.forward();
  }

  @override
  void dispose() {
    _animationController.dispose();
    _jsonController.dispose();
    _countController.dispose();
    _durationController.dispose();
    _shareService.dispose();
    super.dispose();
  }

  String _getCustomInstruction() {
    return buildTestInstruction(
      type: _testType,
      language: _selectedLanguage,
      count: _questionCount,
    );
  }

  /// Parse, validate, normalize, and mirror the accepted JSON back into the
  /// editor. Returns null after showing a user-facing error.
  ParsedTest? _prepareTest({bool showErrors = true}) {
    final raw = _jsonController.text.trim();
    if (raw.isEmpty) {
      if (showErrors) {
        _showError('Please paste the JSON generated by the AI.');
      }
      return null;
    }

    try {
      final test = parseTest(raw, _testType);
      final pretty = test.prettyJson;

      if (_jsonController.text != pretty) {
        _jsonController.value = TextEditingValue(
          text: pretty,
          selection: TextSelection.collapsed(offset: pretty.length),
        );
        if (mounted) setState(() {});
      }

      return test;
    } on TestFormatException catch (e) {
      if (showErrors) _showError(e.message);
      return null;
    } catch (_) {
      if (showErrors) {
        _showError('Failed to parse JSON. Please check the format.');
      }
      return null;
    }
  }

  ({bool valid, String message, int count}) _jsonStatus() {
    final raw = _jsonController.text.trim();
    if (raw.isEmpty) {
      return (valid: false, message: 'Paste JSON to continue', count: 0);
    }

    try {
      final test = parseTest(raw, _testType);
      final count = test.questions.length;
      return (
        valid: true,
        message: 'Valid JSON · $count question${count == 1 ? '' : 's'}',
        count: count,
      );
    } on TestFormatException catch (e) {
      return (valid: false, message: e.message, count: 0);
    } catch (_) {
      return (valid: false, message: 'Invalid JSON', count: 0);
    }
  }

  Future<void> _pickImages() async {
    if (_isPickingImages) return;

    if (_selectedImages.length >= _maxImages) {
      _showError('You can attach up to $_maxImages images.');
      return;
    }

    setState(() => _isPickingImages = true);

    try {
      final images = await _imagePicker.pickMultiImage(
        imageQuality: 80,
        maxWidth: 1600,
        maxHeight: 1600,
      );

      if (!mounted || images.isEmpty) return;

      final valid = <XFile>[];
      for (final image in images) {
        if (await File(image.path).exists()) valid.add(image);
      }

      if (valid.isEmpty) {
        _showError('Could not read the selected image(s).');
        return;
      }

      final remaining = _maxImages - _selectedImages.length;
      final accepted = valid.take(remaining).toList();

      setState(() => _selectedImages.addAll(accepted));

      if (accepted.length < valid.length) {
        _showInfo(
          'Added ${accepted.length} image(s). The limit is $_maxImages.',
        );
      } else {
        _showInfo('Added ${accepted.length} image(s).');
      }
    } on PlatformException catch (e) {
      if (mounted) {
        _showError('Could not pick images: ${e.message ?? e.code}');
      }
    } catch (e) {
      if (mounted) _showError('Could not pick images: $e');
    } finally {
      if (mounted) setState(() => _isPickingImages = false);
    }
  }

  Future<void> _takePhoto() async {
    if (_isPickingImages) return;

    if (!kIsWeb && defaultTargetPlatform == TargetPlatform.linux) {
      _showError(
        'Camera capture is not supported on Linux. Choose images instead.',
      );
      return;
    }

    if (_selectedImages.length >= _maxImages) {
      _showError('You can attach up to $_maxImages images.');
      return;
    }

    setState(() => _isPickingImages = true);

    try {
      if (!kIsWeb && defaultTargetPlatform == TargetPlatform.android) {
        final status = await Permission.camera.request();
        if (!status.isGranted) {
          _showError(
            status.isPermanentlyDenied
                ? 'Camera permission is permanently denied. Enable it in '
                    'Settings to take a photo.'
                : 'Camera permission denied. Allow camera access in Settings.',
          );
          return;
        }
      }

      final photo = await _imagePicker.pickImage(
        source: ImageSource.camera,
        imageQuality: 80,
        maxWidth: 1600,
        maxHeight: 1600,
      );

      if (!mounted || photo == null) return;

      if (!await File(photo.path).exists()) {
        _showError('Could not read the captured photo.');
        return;
      }

      setState(() => _selectedImages.add(photo));
      _showInfo('Photo added.');
    } on PlatformException catch (e) {
      if (!mounted) return;

      String message = 'Camera unavailable.';
      if (e.code == 'camera_access_denied') {
        message = 'Camera permission denied. Allow camera access in Settings.';
      } else if (e.message != null && e.message!.contains('startPreview')) {
        message = 'Camera failed to start. Close other camera apps and retry.';
      } else {
        message = 'Camera error: ${e.message ?? e.code}';
      }
      _showError(message);
    } catch (e) {
      if (mounted) _showError('Camera error: $e');
    } finally {
      if (mounted) setState(() => _isPickingImages = false);
    }
  }

  void _removeImage(int index) {
    setState(() => _selectedImages.removeAt(index));
  }

  void _clearImages() {
    if (_selectedImages.isEmpty) return;
    setState(() => _selectedImages.clear());
  }

  Future<void> _copyInstruction() async {
    try {
      await Clipboard.setData(
        ClipboardData(text: _getCustomInstruction()),
      );
      if (!mounted) return;
      _showInfo(
        'Instruction copied. Paste it into your AI app with the image.',
      );
    } catch (_) {
      if (mounted) _showError('Could not copy the instruction.');
    }
  }

  Future<void> _shareInstruction() async {
    final text = _getCustomInstruction();

    try {
      await Clipboard.setData(ClipboardData(text: text));
    } catch (_) {
      // Sharing may still work even when the clipboard does not.
    }

    if (!mounted) return;

    if (_selectedImages.isNotEmpty &&
        !kIsWeb &&
        defaultTargetPlatform == TargetPlatform.linux) {
      _showError(
        'Attaching images is not supported on Linux. Use the Android app '
        'to share images with the AI.',
      );
      return;
    }

    try {
      final ShareResult result;
      if (_selectedImages.isNotEmpty) {
        result = await Share.shareXFiles(
          _selectedImages,
          text: text,
          subject: 'AI Test Generation Instruction',
        );
      } else {
        result = await Share.shareWithResult(
          text,
          subject: 'AI Test Generation Instruction',
        );
      }

      if (!mounted) return;
      if (result.status == ShareResultStatus.unavailable) {
        _showInfo(
          _selectedImages.isEmpty
              ? 'Instruction copied to clipboard.'
              : 'Images are ready. Attach them manually in the AI app.',
        );
      }
    } catch (e) {
      if (mounted) {
        _showError(
          _selectedImages.isEmpty
              ? 'Could not share the instruction: $e'
              : 'Could not share the images: $e',
        );
      }
    }
  }

  Future<void> _pasteFromClipboard() async {
    try {
      final data = await Clipboard.getData('text/plain');
      if (!mounted) return;

      final text = data?.text?.trim() ?? '';
      if (text.isEmpty) {
        _showInfo('The clipboard is empty. Copy the AI response first.');
        return;
      }

      _jsonController.value = TextEditingValue(
        text: text,
        selection: TextSelection.collapsed(offset: text.length),
      );
      setState(() {});
      _showInfo('Text pasted from clipboard.');
    } catch (_) {
      if (mounted) _showError('Could not read the clipboard.');
    }
  }

  void _clearJson() {
    final previous = _jsonController.text;
    if (previous.isEmpty) return;

    _jsonController.clear();
    setState(() {});

    final messenger = ScaffoldMessenger.of(context);
    messenger
      ..clearSnackBars()
      ..showSnackBar(
        SnackBar(
          content: const Text('JSON cleared'),
          action: SnackBarAction(
            label: 'Undo',
            onPressed: () {
              _jsonController.text = previous;
              setState(() {});
            },
          ),
        ),
      );
  }

  void _formatJson() {
    final test = _prepareTest();
    if (test == null) return;
    _showInfo('JSON formatted and normalized.');
  }

  void _loadSample() {
    final sample = sampleTestJson(_testType, _selectedLanguage);
    _jsonController.value = TextEditingValue(
      text: sample,
      selection: TextSelection.collapsed(offset: sample.length),
    );
    setState(() {});
    _showInfo('Sample ${_testType.label} JSON loaded.');
  }

  void _buildTest() {
    if (_hasRangeWarning) {
      _showError(
        'Enter a question count from 1–100 and a duration from 1–180 minutes.',
      );
      return;
    }

    final test = _prepareTest();
    if (test == null) return;

    FocusScope.of(context).unfocus();
    _navigateToTestPage(test);
  }

  Future<void> _shareTest() async {
    if (_hasRangeWarning) {
      _showError(
        'Enter a question count from 1–100 and a duration from 1–180 minutes.',
      );
      return;
    }

    if (_testType == TestType.creative) {
      _showError(
        'Sharing Creative Questions is not supported yet. '
        'Use Preview to review them.',
      );
      return;
    }

    final test = _prepareTest();
    if (test == null) return;

    final url = AppConfig.testShareApi.trim();
    if (url.isEmpty) {
      _showError('The share service is not configured.');
      return;
    }

    FocusScope.of(context).unfocus();
    setState(() => _isSharing = true);

    final messenger = ScaffoldMessenger.of(context);

    try {
      final code = await _shareService.publish(
        url: url,
        testType: test.type.label,
        language: _selectedLanguage,
        duration: _durationMinutes,
        jsonData: test.normalizedJson,
      );

      if (!mounted) return;
      _showShareCodeDialog(code);
    } on TestShareException catch (e) {
      if (!mounted) return;
      messenger
        ..clearSnackBars()
        ..showSnackBar(
          SnackBar(
            content: Text(e.message),
            backgroundColor: Colors.red.shade600,
            behavior: SnackBarBehavior.floating,
            shape: RoundedRectangleBorder(
              borderRadius: BorderRadius.circular(10),
            ),
          ),
        );
    } catch (e) {
      if (!mounted) return;
      messenger
        ..clearSnackBars()
        ..showSnackBar(
          SnackBar(
            content: Text('Could not share the test: $e'),
            backgroundColor: Colors.red.shade600,
            behavior: SnackBarBehavior.floating,
            shape: RoundedRectangleBorder(
              borderRadius: BorderRadius.circular(10),
            ),
          ),
        );
    } finally {
      if (mounted) setState(() => _isSharing = false);
    }
  }

  void _showShareCodeDialog(String code) {
    final messenger = ScaffoldMessenger.of(context);

    showDialog<void>(
      context: context,
      barrierDismissible: false,
      builder: (dialogContext) => AlertDialog(
        shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(20)),
        title: const Text('Test Published!', textAlign: TextAlign.center),
        content: Column(
          mainAxisSize: MainAxisSize.min,
          children: [
            const Text('Share this code with your friends or students:'),
            const SizedBox(height: 16),
            Container(
              padding: const EdgeInsets.symmetric(horizontal: 20, vertical: 12),
              decoration: BoxDecoration(
                color: Colors.teal.shade50,
                borderRadius: BorderRadius.circular(12),
                border: Border.all(color: Colors.teal.shade200),
              ),
              child: FittedBox(
                fit: BoxFit.scaleDown,
                child: SelectableText(
                  code,
                  style: TextStyle(
                    fontSize: 32,
                    fontWeight: FontWeight.bold,
                    letterSpacing: 8,
                    color: Colors.teal.shade800,
                  ),
                ),
              ),
            ),
          ],
        ),
        actions: [
          TextButton(
            onPressed: () async {
              try {
                await Clipboard.setData(ClipboardData(text: code));
              } catch (_) {
                if (dialogContext.mounted) {
                  _showError('Could not copy the code.');
                }
                return;
              }

              if (!dialogContext.mounted) return;
              Navigator.of(dialogContext).pop();
              messenger.showSnackBar(
                const SnackBar(
                  content: Text('Share code copied to clipboard'),
                ),
              );
            },
            child: const Text('Copy'),
          ),
          TextButton(
            onPressed: () async {
              Navigator.of(dialogContext).pop();
              try {
                await Clipboard.setData(ClipboardData(text: code));
              } catch (_) {
                // The share sheet can still carry the code.
              }
              if (!mounted) return;

              try {
                await Share.share(
                  'Join my test on Pi-QBank with code: $code',
                  subject: 'Pi-QBank Test Code',
                );
              } catch (_) {
                if (mounted) {
                  _showInfo('Share code copied to clipboard.');
                }
              }
            },
            child: const Text('Share'),
          ),
          ElevatedButton(
            onPressed: () => Navigator.of(dialogContext).pop(),
            style: ElevatedButton.styleFrom(
              backgroundColor: Colors.teal.shade600,
              foregroundColor: Colors.white,
              shape: RoundedRectangleBorder(
                borderRadius: BorderRadius.circular(10),
              ),
            ),
            child: const Text('Done'),
          ),
        ],
      ),
    );
  }

  void _navigateToTestPage(ParsedTest test) {
    if (test.type == TestType.mcq) {
      Navigator.push(
        context,
        MaterialPageRoute(
          builder: (context) => MCQTestPage(
            numberOfQuestions: test.questions.length,
            testTimeInMinutes: _durationMinutes,
            aiResponse: test.normalizedJson,
            language: _selectedLanguage,
            aiTopic: test.topic,
            isFromCloud: false,
            showAllQuestions: true,
          ),
        ),
      );
      return;
    }

    if (test.type == TestType.short) {
      Navigator.push(
        context,
        MaterialPageRoute(
          builder: (context) => ShortQuestionPage(
            numberOfQuestions: test.questions.length,
            testTimeInMinutes: _durationMinutes,
            aiResponse: formatShortQuestions(
              test.questions,
              _selectedLanguage,
            ),
            language: _selectedLanguage,
            aiTopic: test.topic,
            isFromCloud: false,
          ),
        ),
      );
      return;
    }

    _showCreativeQuestionsDialog(test.questions, topic: test.topic);
  }

  void _showCreativeQuestionsDialog(
    List<Map<String, dynamic>> questions, {
    required String topic,
  }) {
    final copyText = formatCreativeQuestions(questions, _selectedLanguage);

    showDialog<void>(
      context: context,
      builder: (dialogContext) => AlertDialog(
        title: Text(
          topic.isEmpty
              ? 'Generated Creative Questions'
              : 'Creative Questions · $topic',
        ),
        content: SizedBox(
          width: double.maxFinite,
          height: MediaQuery.sizeOf(dialogContext).height * 0.6,
          child: ListView.separated(
            itemCount: questions.length,
            separatorBuilder: (_, __) => const Divider(),
            itemBuilder: (context, index) {
              final q = questions[index];
              final subQs = (q['sub_questions'] as List?) ?? const [];
              final marksLabel =
                  _selectedLanguage == 'বাংলা' ? 'নম্বর' : 'marks';

              return Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  Text(
                    '${q['question_number'] ?? index + 1}. ${q['stem'] ?? ''}',
                    style: const TextStyle(fontWeight: FontWeight.bold),
                  ),
                  const SizedBox(height: 6),
                  for (final sq in subQs)
                    if (sq is Map)
                      Padding(
                        padding: const EdgeInsets.only(bottom: 4),
                        child: Text(
                          '${sq['label']}) ${sq['text']} '
                          '(${sq['marks']} $marksLabel)',
                        ),
                      ),
                ],
              );
            },
          ),
        ),
        actions: [
          TextButton.icon(
            onPressed: () async {
              try {
                await Clipboard.setData(ClipboardData(text: copyText));
              } catch (_) {
                if (dialogContext.mounted) {
                  _showError('Could not copy the questions.');
                }
                return;
              }

              if (!dialogContext.mounted) return;
              Navigator.of(dialogContext).pop();
              if (mounted) {
                _showInfo('Creative questions copied to clipboard.');
              }
            },
            icon: const Icon(Icons.copy_outlined, size: 18),
            label: const Text('Copy'),
          ),
          TextButton(
            onPressed: () => Navigator.of(dialogContext).pop(),
            child: const Text('Close'),
          ),
        ],
      ),
    );
  }

  void _showError(String message) {
    if (!mounted) return;

    final messenger = ScaffoldMessenger.of(context);
    messenger
      ..clearSnackBars()
      ..showSnackBar(
        SnackBar(
          content: Text(message),
          backgroundColor: Colors.red.shade600,
          behavior: SnackBarBehavior.floating,
          shape: RoundedRectangleBorder(
            borderRadius: BorderRadius.circular(10),
          ),
        ),
      );
  }

  void _showInfo(String message) {
    if (!mounted) return;

    final messenger = ScaffoldMessenger.of(context);
    messenger
      ..clearSnackBars()
      ..showSnackBar(
        SnackBar(
          content: Text(message),
          backgroundColor: Colors.teal.shade600,
          behavior: SnackBarBehavior.floating,
          shape: RoundedRectangleBorder(
            borderRadius: BorderRadius.circular(10),
          ),
        ),
      );
  }

